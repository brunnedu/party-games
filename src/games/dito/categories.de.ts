/**
 * Two categories per card, from different groups: the groups are interleaved, and
 * neighbours share a card.
 */
export function ditoCards(groups = CATEGORY_GROUPS_DE): [string, string][] {
  const longest = Math.max(...groups.map((g) => g.length))
  const mixed = Array.from({ length: longest }, (_, i) =>
    groups.flatMap((g) => g.slice(i, i + 1)),
  ).flat()
  return Array.from({ length: Math.floor(mixed.length / 2) }, (_, i) => [
    mixed[2 * i]!,
    mixed[2 * i + 1]!,
  ])
}
